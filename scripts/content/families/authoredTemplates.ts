/**
 * Authored recognizable silhouettes for Phase 8A pilot.
 * Source of truth: ASCII (# filled, . empty). Titles Russian.
 */

import { parseAscii, type Bitmap } from '../bitmap'
import type { CollectionId } from '../constants'

export interface AuthoredTemplate {
	readonly id: string
	readonly titleRu: string
	readonly collectionId: CollectionId
	readonly family: string
	readonly ascii: readonly string[]
	readonly kind: 'object' | 'pattern'
}

function t(
	id: string,
	titleRu: string,
	collectionId: CollectionId,
	family: string,
	ascii: readonly string[],
	kind: 'object' | 'pattern' = 'object',
): AuthoredTemplate {
	return { id, titleRu, collectionId, family, ascii, kind }
}

/** Parse + dimension of an authored template. */
export function materializeTemplate(template: AuthoredTemplate): {
	readonly bitmap: Bitmap
	readonly width: number
	readonly height: number
} {
	const bitmap = parseAscii(template.ascii)
	return {
		bitmap,
		width: bitmap[0]!.length,
		height: bitmap.length,
	}
}

