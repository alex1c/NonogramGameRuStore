/**
 * Phase 8B.1 replacement pool for weak B250-R1 tail (~25 removals).
 * ~45 NEW distinct production concepts with readable silhouettes.
 * Pattern matches ExpansionTemplate + c() from r2QuotaExpansion.
 * Distinct conceptIds; no procedural noise. Not wired into the pipeline yet.
 */

import { normalizeConceptId, type CollectionId } from '../constants'
import type { ContentKind, SourceKind } from '../types'

/** Local template shape — matches ExpansionTemplate in r2QuotaExpansion. */
export interface ExpansionTemplate {
	readonly id: string
	readonly titleRu: string
	readonly collectionId: CollectionId
	readonly conceptId: string
	readonly compositionId: string
	readonly family: string
	readonly kind: ContentKind
	readonly sourceKind: SourceKind
	readonly ascii: readonly string[]
}

function c(
	id: string,
	titleRu: string,
	collectionId: CollectionId,
	conceptId: string,
	compositionId: string,
	ascii: readonly string[],
	kind: ContentKind = 'object',
	family?: string,
): ExpansionTemplate {
	return {
		id,
		titleRu,
		collectionId,
		conceptId: normalizeConceptId(conceptId),
		compositionId,
		family: family ?? `authored-${normalizeConceptId(conceptId)}`,
		kind,
		sourceKind: 'authored',
		ascii,
	}
}

