function toBitmap(rows: readonly string[]): Bitmap {
	const matrix: Bit[][] = rows.map((row) =>
		[...row].map((ch) => (ch === '#' ? 1 : 0)),
	)
	return freezeBitmap(matrix)
}

function frame5(mask: number): string[] {
	const cells = [
		[1, 1],
		[1, 2],
		[1, 3],
		[2, 1],
		[2, 3],
		[3, 1],
		[3, 2],
		[3, 3],
	] as const
	const g = [
		['#', '#', '#', '#', '#'],
		['#', '.', '.', '.', '#'],
		['#', '.', '#', '.', '#'],
		['#', '.', '.', '.', '#'],
		['#', '#', '#', '#', '#'],
	]
	for (let b = 0; b < 8; b += 1) {
		if (((mask >> b) & 1) === 1) {
			const [r, c] = cells[b]!
			g[r]![c] = '#'
		}
	}
	return g.map((row) => row.join(''))
}

