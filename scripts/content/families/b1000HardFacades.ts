export function buildHardFacadeCandidates(): RawCandidate[] {
	const out: RawCandidate[] = []
	const flips: Array<readonly [number, number]> = [
		[1, 3],
		[1, 11],
		[2, 2],
		[2, 12],
		[3, 1],
		[3, 13],
		[4, 4],
		[4, 10],
		[5, 3],
		[5, 11],
		[6, 2],
		[6, 12],
		[7, 5],
		[7, 9],
		[8, 4],
		[8, 10],
		[9, 3],
		[9, 11],
		[10, 5],
		[10, 9],
		[11, 4],
		[11, 10],
		[2, 5],
		[2, 9],
		[3, 6],
		[3, 8],
		[5, 6],
		[5, 8],
		[6, 5],
		[6, 9],
		[8, 6],
		[8, 8],
		[10, 2],
		[10, 12],
		[11, 6],
		[11, 8],
		[1, 6],
		[1, 8],
		[4, 2],
		[4, 12],
		[7, 1],
		[7, 13],
		[9, 5],
		[9, 7],
		[2, 7],
		[5, 7],
		[8, 7],
		[11, 2],
		[3, 4],
		[3, 10],
		[6, 4],
		[6, 10],
		[10, 6],
		[10, 8],
		[4, 7],
		[9, 1],
		[9, 13],
	]
	for (let i = 0; i < TITLES.length; i += 1) {
		const grid = TRAM.map((row) => [...row])
		const [r0, c0] = flips[i % flips.length]!
		const [r1, c1] = flips[(i * 3 + 1) % flips.length]!
		const [r2, c2] = flips[(i * 5 + 2) % flips.length]!
		for (const [r, c] of [
			[r0, c0],
			[r1, c1],
			[r2, c2],
		] as const) {
			if (grid[r]?.[c] !== undefined && grid[r]![c] !== undefined) {
				grid[r]![c] = grid[r]![c] === '#' ? '.' : '#'
			}
		}
		// Unique pantograph / roof detail
		if (grid[0]) {
			grid[0]![2 + (i % 11)] = '#'
		}
		const slug = `hard-tram-${i + 1}`
		out.push({
			id: `s8c-hdtram-${i + 1}`,
			titleRu: TITLES[i]!,
			collectionId: 'transport',
			conceptId: normalizeConceptId(slug),
			compositionId: `tram-var-${i + 1}`,
			family: `scale-${normalizeConceptId(slug)}`,
			variant: `tram-var-${i + 1}`,
			kind: 'object',
			sourceKind: 'procedural',
			contentRole: 'production',
			bitmap: toBitmap(grid.map((row) => row.join(''))),
			seed: 992_000 + i,
		})
	}
	return out
}
