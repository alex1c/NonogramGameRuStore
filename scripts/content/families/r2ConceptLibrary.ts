export interface ConceptTemplate {
	readonly id: string
	readonly titleRu: string
	readonly collectionId: CollectionId
	readonly conceptId: string
	readonly compositionId: string
	readonly family: string
	readonly kind: ContentKind
	readonly sourceKind: SourceKind
	readonly contentRole?: ContentRole
	readonly ascii: readonly string[]
}

function c(
	id: string,
	titleRu: string,
	collectionId: CollectionId,
	conceptId: string,
	compositionId: string,
	ascii: readonly string[],
	kind: ContentKind = 'object',
	family?: string,
	contentRole: ContentRole = 'production',
): ConceptTemplate {
	return {
		id,
		titleRu,
		collectionId,
		conceptId: normalizeConceptId(conceptId),
		compositionId,
		family: family ?? `authored-${normalizeConceptId(conceptId)}`,
		kind,
		sourceKind: 'authored',
		contentRole,
		ascii,
	}
}

export function materializeConcept(template: ConceptTemplate): {
	readonly bitmap: Bitmap
	readonly width: number
	readonly height: number
} {
	const bitmap = parseAscii(template.ascii)
	return {
		bitmap,
		width: bitmap[0]!.length,
		height: bitmap.length,
	}
}

